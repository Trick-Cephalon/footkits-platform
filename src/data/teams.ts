export const teamsByContinent = {
  brasil: teams.filter((t) => t.continent === 'brasil'),
  europa: teams.filter((t) => t.continent === 'europa'),
  'america-sul': teams.filter((t) => t.continent === 'america-sul'),
  selecoes: teams.filter((t) => t.continent === 'selecoes'),
}

export function getTeamById(id: string): Team | undefined {
  return teams.find((t) => t.id === id)
}

export function searchTeams(query: string): Team[] {
  const q = query.toLowerCase()
  return teams.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.shortName.toLowerCase().includes(q) ||
      t.country.toLowerCase().includes(q) ||
      t.league.toLowerCase().includes(q)
  )
}
